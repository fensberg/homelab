// Command generate writes a Go file for each fact in a directory: generate
// <facts> <out>. Each fact is a JSON object of names and values; a name that
// begins with an underscore is a comment and is not a fact.
//
// A string, a number or a true or false is a constant. A list of objects is a
// table: a struct type of the fields every entry has, and a slice of the
// entries in the order the file gives them. Every entry has the same fields,
// each a string, a number or a true or false of one kind throughout, so a
// table reads the same whichever entry is read. Anything else is refused
// rather than half written.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

// generated is the suffix of every file this writes, and of no other.
const generated = ".generated.go"

func main() {
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: generate <facts> <out>")
		os.Exit(2)
	}
	if err := write(os.Args[1], os.Args[2]); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

// write makes out hold one generated file for each fact in facts and no
// other: a file left from a fact since removed is removed with it.
func write(facts, out string) error {
	sources, err := filepath.Glob(filepath.Join(facts, "*.json"))
	if err != nil {
		return err
	}
	if len(sources) == 0 {
		return fmt.Errorf("%s holds no fact, so there is nothing to generate", facts)
	}
	made := map[string]bool{}
	for _, src := range sources {
		raw, err := os.ReadFile(src)
		if err != nil {
			return err
		}
		name := strings.TrimSuffix(filepath.Base(src), ".json")
		body, err := render(name, raw)
		if err != nil {
			return fmt.Errorf("%s: %w", src, err)
		}
		file := name + generated
		made[file] = true
		if err := os.WriteFile(filepath.Join(out, file), body, 0o644); err != nil {
			return err
		}
	}
	left, err := filepath.Glob(filepath.Join(out, "*"+generated))
	if err != nil {
		return err
	}
	for _, f := range left {
		if !made[filepath.Base(f)] {
			if err := os.Remove(f); err != nil {
				return err
			}
		}
	}
	return nil
}

// render is the Go file of one fact: a constant for each of its values,
// named for the fact and the value.
func render(name string, raw []byte) ([]byte, error) {
	var fact map[string]any
	dec := json.NewDecoder(bytes.NewReader(raw))
	dec.UseNumber()
	if err := dec.Decode(&fact); err != nil {
		return nil, fmt.Errorf("not a JSON object of names and values: %w", err)
	}
	var keys []string
	for k := range fact {
		if !strings.HasPrefix(k, "_") {
			keys = append(keys, k)
		}
	}
	if len(keys) == 0 {
		return nil, fmt.Errorf("holds no value, only comments")
	}
	sort.Strings(keys)
	var constants, tables strings.Builder
	for _, k := range keys {
		named := identifier(name) + identifier(k)
		if entries, ok := fact[k].([]any); ok {
			table, err := tableOf(named, entries)
			if err != nil {
				return nil, fmt.Errorf("%s: %w", k, err)
			}
			tables.WriteString(table)
			continue
		}
		literal, _, ok := scalar(fact[k])
		if !ok {
			return nil, fmt.Errorf("%s is not a string, a number, a true or false or a list of objects, so it cannot be written as Go", k)
		}
		fmt.Fprintf(&constants, "\t%s = %s\n", named, literal)
	}
	var b strings.Builder
	fmt.Fprintf(&b, "// Code generated by go generate from config/facts/%s.json. DO NOT EDIT.\n\n", name)
	b.WriteString("package facts\n")
	if constants.Len() > 0 {
		b.WriteString("\nconst (\n" + constants.String() + ")\n")
	}
	b.WriteString(tables.String())
	return format.Source([]byte(b.String()))
}

// scalar is a value written as a Go literal, and the Go type it is: a
// string, a whole number, a number with a fraction, or a true or false.
func scalar(v any) (literal, kind string, ok bool) {
	switch v := v.(type) {
	case string:
		return fmt.Sprintf("%q", v), "string", true
	case json.Number:
		if _, err := v.Int64(); err == nil {
			return v.String(), "int", true
		}
		return v.String(), "float64", true
	case bool:
		return fmt.Sprint(v), "bool", true
	}
	return "", "", false
}

// tableOf is a list of objects as a struct type and a slice of it, in the
// order given.
func tableOf(named string, entries []any) (string, error) {
	if len(entries) == 0 {
		return "", fmt.Errorf("is an empty list, so there are no fields to make a table of")
	}
	var fields []string
	kinds := map[string]string{}
	rows := make([][]string, len(entries))
	for i, e := range entries {
		entry, ok := e.(map[string]any)
		if !ok {
			return "", fmt.Errorf("entry %d is not an object", i)
		}
		if i == 0 {
			for f := range entry {
				fields = append(fields, f)
			}
			sort.Strings(fields)
		}
		if len(entry) != len(fields) {
			return "", fmt.Errorf("entry %d has %d fields and the first has %d: every entry has the same fields", i, len(entry), len(fields))
		}
		for _, f := range fields {
			v, has := entry[f]
			if !has {
				return "", fmt.Errorf("entry %d has no %s, which the first has: every entry has the same fields", i, f)
			}
			literal, kind, ok := scalar(v)
			if !ok {
				return "", fmt.Errorf("entry %d's %s is not a string, a number or a true or false", i, f)
			}
			if was, seen := kinds[f]; seen && was != kind {
				// A whole number beside one with a fraction is a number
				// with a fraction that happens to be whole.
				if numbers := map[string]bool{"int": true, "float64": true}; !numbers[was] || !numbers[kind] {
					return "", fmt.Errorf("%s is a %s in one entry and a %s in another", f, was, kind)
				}
				kind = "float64"
			}
			kinds[f] = kind
			rows[i] = append(rows[i], identifier(f)+": "+literal)
		}
	}
	var b strings.Builder
	fmt.Fprintf(&b, "\n// %sEntry is one entry of %s.\ntype %sEntry struct {\n", named, named, named)
	for _, f := range fields {
		fmt.Fprintf(&b, "\t%s %s\n", identifier(f), kinds[f])
	}
	fmt.Fprintf(&b, "}\n\nvar %s = []%sEntry{\n", named, named)
	for _, row := range rows {
		b.WriteString("\t{" + strings.Join(row, ", ") + "},\n")
	}
	b.WriteString("}\n")
	return b.String(), nil
}

// identifier is a name written with dashes or underscores, as Go writes an
// exported one: not_yet_clean is NotYetClean.
func identifier(name string) string {
	var b strings.Builder
	for _, part := range strings.FieldsFunc(name, func(r rune) bool { return r == '-' || r == '_' }) {
		b.WriteString(strings.ToUpper(part[:1]) + part[1:])
	}
	return b.String()
}
